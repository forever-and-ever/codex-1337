#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.13"
# dependencies = ["colour-science==0.4.7", "numpy>=2.3"]
# ///
"""Smelt warpaint specs into packs and proofs, or check that they are current.

The laws derive every role and ramp from a spec (laws.py) in the appearance frame
(appearance.py); the proof checks every pair the TUI declares it paints (vocabulary.py, from
roles.json); the pack is what the TUI embeds. `--check` is the gate: it fails when a pack or
proof differs from its spec, when a spec breaks the doctrine, when the vocabulary and the
laws disagree, or when a live capture shows chrome no pack paints.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True  # sibling modules stay uncompiled in the worktree

from laws import Invalid, Pack, Spec, smelt
from proof import TUI, prove
from vocabulary import LIVERY_COUNT, Figure, Ground, Syntax

HERE = Path(__file__).resolve().parent
CLIENT = {"reset", "ground:canvas", "ground:trough", "ground:dais"}
"""The grounds the client speaks on, where bold default ink is a label the pack must paint."""


def audit(capture: Path) -> list[str]:
    """Chrome in a live capture that no pack paints: a literal color, which the pack never
    decides, or bold default ink on the client's grounds, a label left unpainted."""
    faults = []
    for y, row in enumerate(json.loads(capture.read_text())["rows"]):
        for run in row:
            text = run["text"].strip()
            named = (run["fg"],) * bool(text) + (run["bg"],)
            for name in (name for name in named if name.startswith(("rgb:", "xterm:"))):
                faults.append(f"{capture.stem} row {y}: {text or 'a fill'!r} paints the literal {name}")
            if text and run["fg"] == "reset" and "bold" in run["mods"] and run["bg"] in CLIENT:
                faults.append(f"{capture.stem} row {y}: {text!r} is bold default ink, a label left unpainted")
    return faults


def emit(pack: Pack) -> str:
    spec = pack.spec

    def ramp(key: str, swatches: tuple) -> list[str]:
        return [f"{key} = [", *(f'  "{s.hex}",' for s in swatches), "]"]

    def table(family: type) -> list[str]:
        return ["", f"[{family.__name__.lower()}]", *(f'{member.value} = "{pack.roles[member].hex}"' for member in family)]

    style = [f"{syntax.value} = [" + ", ".join(f'"{m}"' for m in modifiers) + "]" for syntax, modifiers in spec.style.items()]
    return "\n".join(
        [
            f"# {spec.name}: generated by scripts/warpaint/smelt.py from specs/{spec.name}.toml.",
            "# Edit the spec and re-smelt; a hand edit here is unprovable and the next smelt erases it.",
            *(f"# {line}".rstrip() for line in spec.stance.splitlines()),
            *ramp("livery", pack.livery),
            *ramp("heat", pack.heat),
            *ramp("terminal", pack.terminal),
            *table(Ground),
            *table(Figure),
            *table(Syntax),
            *(["", "[style]", *style] if style else []),
        ]
    ) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("specs", nargs="*", type=Path, help="spec files; default: specs/*.toml")
    parser.add_argument("--packs", type=Path, default=TUI / "warpaint/packs")
    parser.add_argument("--proofs", type=Path, default=HERE / "proofs")
    parser.add_argument("--check", action="store_true", help="fail unless every pack and proof is current and faultless")
    args = parser.parse_args()
    failed = False
    specs = sorted(args.specs or (HERE / "specs").glob("*.toml"))
    for path in specs:
        try:
            pack = smelt(Spec.load(path))
        except Invalid as error:
            print(error)
            return 2
        unsolved = {*Ground, *Figure, *Syntax} - pack.roles.keys()
        if unsolved or not LIVERY_COUNT[0] <= len(pack.livery) <= LIVERY_COUNT[1]:
            print(f"{pack.spec.name}: the laws leave {sorted(map(str, unsolved))} unsolved or the livery out of range")
            return 2
        report, faults = prove(pack)
        outputs = {args.packs / f"{pack.spec.name}.toml": emit(pack), args.proofs / f"{pack.spec.name}.md": report}
        for target, content in outputs.items():
            if not args.check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content)
            elif not target.exists() or target.read_text() != content:
                print(f"{pack.spec.name}: {target.name} differs from its spec; re-run smelt.py")
                failed = True
        for fault in faults:
            print(f"{pack.spec.name}: {fault}")
        failed = failed or bool(faults)
        rings = ", ".join(f"{ring.label} {ring.level:.1f} ({ring.held_by} over {ring.over})" for ring in pack.rings)
        print(f"{pack.spec.name}: {rings}; {len(faults)} faults")
    if not args.specs:
        smelted = {path.stem for path in specs}
        for directory, suffix in ((args.packs, ".toml"), (args.proofs, ".md")):
            for stale in sorted(p for p in directory.glob(f"*{suffix}") if p.stem not in smelted):
                if args.check:
                    print(f"{stale.name} has no spec")
                    failed = True
                else:
                    stale.unlink()
        if args.check:
            for capture in sorted((HERE / "captures").glob("*.json")):
                for fault in audit(capture):
                    print(fault)
                    failed = True
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
